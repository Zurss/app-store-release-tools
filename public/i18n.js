export function translate(language, key, params = {}) {
  const template = catalogs[language === 'ru' ? 'ru' : 'en'][key];
  if (template === undefined) throw new Error(`Unknown translation key: ${key}`);
  return template.replace(/\{([a-zA-Z]+)\}/g, (match, name) => {
    if (!Object.hasOwn(params, name)) return match;
    const value = params[name];
    return String(value && typeof value === 'object' && typeof value.en === 'string' && typeof value.ru === 'string'
      ? value[language === 'ru' ? 'ru' : 'en'] : value);
  });
}
